#!/bin/bash

# X3 Docker Entrypoint
# Reads x3.conf-dist, replaces every %X3_...% placeholder with the value of
# the environment variable of that name, and writes out x3.conf.  If that
# cannot be done completely the script exits non-zero and X3 is not started.

BASECONFDIST=/x3/x3src/docker/x3.conf-dist
BASECONF=/x3/data/x3.conf

# Marker stamped as the first line of every conf THIS script generates.
# Regeneration policy:
#   - no x3.conf                -> generate (and stamp the marker)
#   - x3.conf with the marker   -> regenerate: env + template are the source
#                                  of truth, so config changes actually land
#                                  on restart instead of freezing at first
#                                  container start
#   - x3.conf without the marker -> user-managed (e.g. volume-mounted);
#                                  never touched
GENMARKER='// GENERATED BY dockerentrypoint.sh from x3.conf-dist. Do not hand-edit: this file is REGENERATED ON EVERY CONTAINER START while this marker is the first line. To manage x3.conf yourself, replace it with a file that lacks this marker.'

# How a value reaches x3.conf.  Every %X3_...% placeholder in the template
# is one of two kinds:
#
#   scalar  the placeholder sits INSIDE a double-quoted conf string, e.g.
#               "password" "%X3_UPLINK_PASSWORD%";
#           The variable holds the plain value.  X3's conf reader
#           (src/recdb.c, parse_qstring) ends a string at '"' and decodes
#           backslash escapes, so '\' and '"' in the value are escaped here;
#           the string X3 ends up with is the variable's value, byte for byte.
#
#   list    the placeholder is the whole body of a conf string list, e.g.
#               "support_channel" (%X3_SUPPORT_CHANNEL%);
#           The variable holds plain items separated by commas
#           (X3_SUPPORT_CHANNEL=#Operations,#Help).  Each item is trimmed,
#           escaped as above and quoted; empty items are dropped.  An item
#           already wrapped in double quotes (the form this variable took
#           before: "#Operations", "#Help") has that pair of quotes removed
#           first, so old values keep working.
#
# The variables named in CONF_LIST_VARS are lists; all others are scalars.
CONF_LIST_VARS=" X3_SUPPORT_CHANNEL "

# Variables that may be set to the empty string, and what that means to X3.
# Any other variable that is set but empty is an error: X3 would read "" as
# 0, or try to use an empty name, where the operator almost certainly meant
# something else.  Leave such a variable unset to get its default.
#
#   X3_AUTO_OPER            no modes are set on opers when they auth, i.e.
#                           auto-oper is off (nickserv.c tests *auto_oper)
#   X3_AUTO_OPER_PRIVS      no privileges are sent with auto-oper
#   X3_GENERAL_BIND_ADDRESS the uplink socket is not bound to a local
#                           address (main-common.c: getaddrinfo("") fails
#                           and bind_addr stays NULL)
#   X3_HIDDEN_HOST_PREFIX   no prefix (nothing in src/ reads this key today)
#   X3_LDAP_ADMIN_DN        no admin bind, as if the key were left out:
#   X3_LDAP_ADMIN_PASS      password checks (a bind as the user) still work,
#                           searches and writes need the admin, so they
#                           fail and are logged (x3ldap.c ldap_do_admin_bind)
#   X3_LDAP_FIELD_OSLEVEL   the OpServ level is not stored in LDAP
#                           (x3ldap.c and nickserv.c test *ldap_field_oslevel)
#   X3_LDAP_FILTER          accounts are searched by name alone, with no
#                           extra filter (x3ldap.c builds "(&%s(attr=name))")
#   X3_SUPPORT_CHANNEL      an empty list: no support channels
EMPTY_OK=" X3_AUTO_OPER X3_AUTO_OPER_PRIVS X3_GENERAL_BIND_ADDRESS X3_HIDDEN_HOST_PREFIX X3_LDAP_ADMIN_DN X3_LDAP_ADMIN_PASS X3_LDAP_FIELD_OSLEVEL X3_LDAP_FILTER X3_SUPPORT_CHANNEL "

# conf_escape VALUE: set REPLY to VALUE escaped for use between the double
# quotes of an x3.conf string.
conf_escape() {
    local bs='\' dq='"'
    REPLY=$1
    REPLY=${REPLY//"$bs"/"$bs$bs"}
    REPLY=${REPLY//"$dq"/"$bs$dq"}
}

# conf_list VALUE: set REPLY to the body of an x3.conf string list built from
# the comma-separated items of VALUE ('a, b' -> '"a", "b"').
conf_list() {
    local rest=$1 item out=
    while [ -n "$rest" ]; do
        case "$rest" in
            *,*) item=${rest%%,*}; rest=${rest#*,} ;;
            *)   item=$rest; rest= ;;
        esac
        # Trim leading and trailing whitespace.
        item=${item#"${item%%[![:space:]]*}"}
        item=${item%"${item##*[![:space:]]}"}
        # Old form: the item carries its own conf quotes.
        case "$item" in
            \"*\") item=${item:1:${#item}-2} ;;
        esac
        [ -n "$item" ] || continue
        conf_escape "$item"
        out="${out:+$out, }\"$REPLY\""
    done
    REPLY=$out
}

# die MESSAGE: report a fatal error and stop, before X3 is started.
die() {
    printf 'dockerentrypoint: ERROR: %s\n' "$*" >&2
    [ -n "$GENTMP" ] && rm -f "$GENTMP"
    exit 1
}

# render_template: write the template to stdout with every %X3_NAME%
# replaced by CONF_VALUE[NAME].  The template is read once and substituted
# text is never looked at again, so a value may contain anything -- '&',
# '|', '\', even text that looks like a placeholder -- without being
# reinterpreted.  Only %X3_...% is a placeholder: the other percent tokens
# the template contains on purpose (%ip% and %txt% in the DNSBL reasons)
# pass through untouched.  A placeholder with no CONF_VALUE entry is left
# as it is and its name is added to UNRESOLVED, so the caller can refuse
# the result.
render_template() {
    local LC_ALL=C re='%(X3_[A-Z0-9_]+)%' line rest name
    UNRESOLVED=
    while IFS= read -r line || [ -n "$line" ]; do
        rest=$line
        line=
        while [[ $rest =~ $re ]]; do
            name=${BASH_REMATCH[1]}
            line+=${rest%%"%$name%"*}
            rest=${rest#*"%$name%"}
            if [ -n "${CONF_VALUE[$name]+x}" ]; then
                line+=${CONF_VALUE[$name]}
            else
                line+="%$name%"
                case " $UNRESOLVED " in
                    *" $name "*) ;;
                    *) UNRESOLVED="${UNRESOLVED:+$UNRESOLVED }$name" ;;
                esac
            fi
        done
        printf '%s\n' "$line$rest" || return 1
    done < "$BASECONFDIST"
}

if [ -f "$BASECONF" ] && ! head -n 1 "$BASECONF" | grep -qF 'GENERATED BY dockerentrypoint.sh'; then
    echo "Found user-managed config at $BASECONF (no generation marker), leaving it alone"
else
    echo "Generating $BASECONF from template..."

    # Defaults.  "${VAR=default}" applies only when VAR is UNSET: a variable
    # that is set to the empty string is kept empty (see EMPTY_OK below).
    : "${X3_GENERAL_NAME=x3.network}"
    : "${X3_GENERAL_BIND_ADDRESS=127.0.0.1}"
    : "${X3_GENERAL_DESCRIPTION=Network Services}"
    : "${X3_GENERAL_DOMAIN=example.com}"
    : "${X3_GENERAL_NUMERIC=199}"
    : "${X3_UPLINK_ADDRESS=127.0.0.1}"
    : "${X3_UPLINK_PORT=8888}"
    : "${X3_UPLINK_PASSWORD=changeme}"

    # Server block
    # 8 = Nefarious 1.3.x; 9 = Nefarious 2.0.x (nefarious2) — must match your ircd.
    : "${X3_SERVER_TYPE=8}"
    : "${X3_HIDDEN_HOST_TYPE=1}"
    # MUST match the ircd's HOST_HIDING_KEY* F:lines; change in production —
    # stock keys make style-2 cloaks predictable.
    : "${X3_HIDDEN_HOST_KEY1=45432}"
    : "${X3_HIDDEN_HOST_KEY2=76934}"
    : "${X3_HIDDEN_HOST_KEY3=98336}"
    : "${X3_HIDDEN_HOST_PREFIX=NETWORK}"

    # OpServ clone-G-line threshold (untrusted_max).  Default 6 (stock).
    # 0 disables it — testbeds set X3_UNTRUSTED_MAX=0 in .env.local so harness
    # connection volume from a single host isn't auto-G-lined.
    : "${X3_UNTRUSTED_MAX=6}"

    # OpServ / ChanServ / Global identity + limits
    : "${X3_OPSERV_NICK=O3}"
    : "${X3_OPSERV_HOSTNAME=X3.Services}"
    : "${X3_DEBUG_CHANNEL=#TheOps}"
    : "${X3_ALERT_CHANNEL=#TheOps}"
    : "${X3_STAFF_AUTH_CHANNEL=#OperServ}"
    : "${X3_CLONE_GLINE_DURATION=2h}"
    : "${X3_CHANSERV_NICK=X3}"
    : "${X3_OFF_CHANNEL=no}"
    : "${X3_MAX_OWNED=2}"
    : "${X3_MAX_CHAN_USERS=512}"
    # A list: channels separated by commas (see CONF_LIST_VARS above).
    : "${X3_SUPPORT_CHANNEL=#Operations,#Help}"
    : "${X3_GLOBAL_NICK=Global}"
    # Also used by the snoop module (templatized with the other modules).
    : "${X3_SNOOP_CHANNEL=#MrSnoopy}"

    # Modules
    : "${X3_SOCKCHECK_MAX_SOCKETS=0}"
    : "${X3_SOCKCHECK_GLINE_DURATION=1d}"
    : "${X3_TRACK_CHANNEL=#MrPeanuts}"
    : "${X3_MEMOSERV_BOT=MemoServ}"
    : "${X3_MEMO_EXPIRY=30d}"
    : "${X3_MEMO_LIMIT=30}"
    # qserver: no shipped literal credential — generate a random password
    # when the deployment doesn't provide one.
    : "${X3_QSERVER_PASSWORD=$(tr -dc 'A-Za-z0-9' </dev/urandom | head -c 16)}"
    : "${X3_BLACKLIST_GLINE_DURATION=1h}"

    # Mail — disabled by default: the image ships no MTA at
    # /usr/sbin/sendmail, so "enabled" only meant every cookie mail
    # failed at sendmail exec time.  Set X3_MAIL_ENABLE=1 (and a working
    # mailer or SMTP server) to turn it on.
    : "${X3_MAIL_ENABLE=0}"
    : "${X3_MAIL_MAILER=/usr/sbin/sendmail}"
    : "${X3_MAIL_SMTP_SERVER=localhost}"
    : "${X3_MAIL_SMTP_SERVICE=smtp}"

    # Databases
    : "${X3_DB_SAVE_FREQUENCY=30m}"

    # NickServ (AuthServ) defaults
    : "${X3_NICKSERV_NICK=AuthServ}"
    : "${X3_DEFAULT_MAXLOGINS=3}"
    : "${X3_HARD_MAXLOGINS=10}"
    : "${X3_AUTO_OPER=+oxwgs}"
    : "${X3_AUTO_OPER_PRIVS=CHAN_LIMIT SHOW_INVIS SHOW_ALL_INVIS KILL LOCAL_KILL REHASH RESTART DIE JUPE LOCAL_JUPE OPMODE WHOX SEE_CHAN PROPAGATE DISPLAY SEE_OPERS WIDE_GLINE FORCE_OPMODE REMOTEREHASH CHECK SEE_SECRET_CHAN WIDE_SHUN WIDE_ZLINE LIST_CHAN}"
    : "${X3_PASSWD_MIN_LENGTH=4}"
    : "${X3_PASSWD_MIN_DIGITS=0}"
    : "${X3_PASSWD_MIN_UPPER=0}"
    : "${X3_PASSWD_MIN_LOWER=0}"
    : "${X3_EMAIL_ENABLED=0}"
    : "${X3_EMAIL_REQUIRED=0}"
    : "${X3_COOKIE_TIMEOUT=2d}"
    : "${X3_ACCOUNTS_PER_EMAIL=1}"
    # Derived from X3_GENERAL_DOMAIN (set above) unless overridden.
    : "${X3_TITLEHOST_SUFFIX=${X3_GENERAL_DOMAIN}}"

    # LDAP defaults (disabled unless overridden)
    : "${X3_LDAP_ENABLE=0}"
    : "${X3_LDAP_WRITEBACK=0}"
    : "${X3_LDAP_URI=ldap://localhost:389}"
    : "${X3_LDAP_BASE=ou=users,dc=example,dc=net}"
    : "${X3_LDAP_DN_FMT=uid=%s,ou=users,dc=example,dc=net}"
    : "${X3_LDAP_ADMIN_DN=cn=admin,dc=example,dc=net}"
    : "${X3_LDAP_ADMIN_PASS=changeme}"
    : "${X3_LDAP_FIELD_ACCOUNT=uid}"
    : "${X3_LDAP_FIELD_PASSWORD=userPassword}"
    : "${X3_LDAP_FIELD_EMAIL=mail}"
    : "${X3_LDAP_FIELD_OSLEVEL=X3AccountLevel}"
    : "${X3_LDAP_FILTER=(objectClass=inetOrgPerson)}"
    : "${X3_LDAP_AUTOCREATE=1}"
    : "${X3_LDAP_TIMEOUT=10}"

    # Put the value of every placeholder the template uses into conf syntax
    # (see CONF_LIST_VARS).  A value with a line break is refused: a conf
    # string cannot span lines, so it could only produce a file X3 rejects
    # or misreads.  So is an empty value X3 has no meaning for (see EMPTY_OK).
    declare -A CONF_VALUE=()
    errors=
    seen=
    placeholders=$(grep -oE '%X3_[A-Z0-9_]+%' "$BASECONFDIST")
    [ $? -le 1 ] || die "cannot read the template $BASECONFDIST"
    while read -r placeholder; do
        [ -n "$placeholder" ] || continue
        # Extract variable name (remove the % signs)
        varname="${placeholder:1:-1}"
        case " $seen " in *" $varname "*) continue ;; esac
        seen+=" $varname"

        # An unset variable gets no entry: render_template reports it.
        [ -n "${!varname+x}" ] || continue

        # Get the value from environment (indirect expansion)
        value="${!varname}"

        if [ -z "$value" ]; then
            case "$EMPTY_OK" in
                *" $varname "*) ;;
                *)
                    errors+="  $varname is set but empty; unset it to get the default, or give it a value"$'\n'
                    continue ;;
            esac
        fi

        case "$value" in
            *$'\n'*|*$'\r'*)
                errors+="  $varname contains a line break"$'\n'
                continue ;;
        esac
        case "$CONF_LIST_VARS" in
            *" $varname "*) conf_list "$value" ;;
            *)              conf_escape "$value" ;;
        esac
        CONF_VALUE[$varname]=$REPLY
    done <<< "$placeholders"
    [ -z "$errors" ] || die "refusing to generate $BASECONF:"$'\n'"${errors%$'\n'}"

    # Render into a temp file with the marker as its first line, then put
    # it in place, so a crash mid-generation never leaves a half-written
    # marker-less (= treated as user-managed) conf behind.
    GENTMP="$BASECONF.gen.$$"
    { printf '%s\n' "$GENMARKER"; render_template; } > "$GENTMP"

    # Never start X3 on a conf that still holds a placeholder: X3 would take
    # the literal %X3_...% text as the value (as a password, for one).
    [ -z "$UNRESOLVED" ] || die "refusing to generate $BASECONF: no value for ${UNRESOLVED// /, }"

    cat "$GENTMP" > "$BASECONF"
    rm -f "$GENTMP"

    echo "Generated $BASECONF from template"
fi

# Run the command passed to docker (CMD from Dockerfile)
exec "$@"
